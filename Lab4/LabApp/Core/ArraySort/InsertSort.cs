namespace LabApp.Core.ArraySort;

/// <summary>
/// Сортировка простыми вставками (InsertSort) — квадратичный алгоритм. Берём числа по одному
/// слева направо: каждое новое число («взятое», оно «в руке») вставляем на его место среди
/// уже разобранных — сдвигая большие (при убывании — меньшие) на позицию вправо, пока не
/// найдём место. На уже отсортированном массиве сравнений всего n-1 — лучший случай,
/// худший (обратно отсортированный) — n(n-1)/2 сравнений и столько же сдвигов.
/// Вызовы builder всегда безусловные (счётчики нужны и в тихом режиме), строки описаний
/// строятся только в режиме трассировки — тернарные операторы не дают их собирать при замерах.
/// </summary>
public sealed class InsertSort : IArraySortAlgorithm
{
    public string Id => "insert";
    public string Title => "InsertSort (вставками)";
    public string Group => ArraySortGroups.Quadratic;
    public string Badge => "O(n²)";
    public string PassesLabel => "вставок";
    public int MemorySlots => 2;
    public string ShortInfo =>
        "Берём числа по одному и вставляем каждое на его место среди уже разобранных: большие сдвигаем вправо, " +
        "ставим взятое в освободившееся место. В памяти: «взятое» число и то, с которым сравниваем.";

    public void Sort(ArrayEntry[] a, bool descending, ArraySortTraceBuilder b)
    {
        int n = a.Length;
        b.Phase("Знакомство",
            $"Перед нами массив из {n} чисел. Сортировка вставками работает как карточки в руке: " +
            "берём числа по одному слева направо и вставляем каждое на его место среди уже разобранных — " +
            "те, что стоят «не туда», сдвигаются на позицию вправо и освобождают место. " +
            "На уже отсортированном массиве вставкам хватит n-1 сравнений, а на обратно отсортированном " +
            "будет n·(n-1)/2 — худший случай. " +
            $"Порядок: {(descending ? "по убыванию" : "по возрастанию")}.");

        for (int x = 1; x < n; x++)
        {
            ArrayEntry key = a[x]; // «взяли число в руку»: слот a[x] считаем свободным
            int hole = x;          // дырка, в которую встанет взятое число
            b.PassNext("Вставка", $"берём «{key.Value}» (позиция {x})",
                b.Active
                    ? $"Вставка {x}: в руке число «{key.Value}» из позиции {x}. Ищем его место среди " +
                      $"уже отсортированных позиций [0..{x - 1}] — идём справа налево и сдвигаем числа, " +
                      $"которые должны стоять позже «{key.Value}»."
                    : null,
                RangeIds(a, 0, x), $"В памяти «взятое» число «{key.Value}».");

            int y = x - 1;
            while (y >= 0)
            {
                bool keyFirst = Before(key.Value, a[y].Value, descending);
                b.Compare(y, hole,
                    b.Active
                        ? $"Сравниваем «взятое» «{key.Value}» с «{a[y].Value}» (позиция {y}): " +
                          (keyFirst
                            ? $"«{key.Value}» должно стоять раньше «{a[y].Value}» — сдвигаем «{a[y].Value}» " +
                              $"на позицию вправо и ищем дальше."
                            : $"«{key.Value}» стоит после «{a[y].Value}» — место найдено: позиция {hole}.")
                        : null,
                    b.Active
                        ? $"⚖ Сравнение №{b.Comparisons + 1}: вставки — «{key.Value}» vs «{a[y].Value}» → " +
                          (keyFirst ? $"сдвигаем «{a[y].Value}» вправо" : $"место — позиция {hole}")
                        : null,
                    $"В памяти «взятое» «{key.Value}» и сравниваемое «{a[y].Value}».",
                    memory: [key.Id, a[y].Id]);
                if (!keyFirst) break;

                a[hole] = a[y]; // сдвиг: число переезжает на позицию вправо, дырка — на его место
                b.Shift(y, hole,
                    b.Active
                        ? $"Сдвинули «{a[y].Value}» с позиции {y} на позицию {hole} — освободили место для «{key.Value}»."
                        : null,
                    b.Active
                        ? $"↔ Перестановка №{b.Moves + 1}: «{a[y].Value}»: позиция {y} → {hole} (вставки)"
                        : null,
                    $"В памяти «взятое» число «{key.Value}» — оно сейчас «в руке», не в массиве.");
                hole = y;
                y--;
            }

            a[hole] = key; // взятое число опускается на своё место — это не обмен, счётчик не растёт
            b.Place(hole,
                b.Active
                    ? (hole == x
                        ? $"«{key.Value}» больше ничего в отсортированной части — оно уже на своём месте (позиция {hole})."
                        : $"Опускаем «{key.Value}» в освободившуюся позицию {hole} — вставка закончена.")
                    : null,
                b.Active
                    ? $"✓ Вставка: «{key.Value}» → позиция {hole}"
                    : null,
                "Число вернулось в массив, память свободна.");
        }

        if (n > 0) b.MarkPlaced(Enumerable.Range(0, n).ToArray());
        b.Done(
            n == 0
                ? "Массив пустой — сортировать нечего."
                : $"Готово: все числа стоят по {(descending ? "убыванию" : "возрастанию")}. " +
                  $"Сравнений — {b.Comparisons}, перестановок (сдвигов) — {b.Moves}, вставок — {b.Passes}.");
    }

    // ---------------- служебные ----------------

    /// <summary>Должно ли число x стоять раньше числа y с учётом направления сортировки.</summary>
    private static bool Before(int x, int y, bool desc) => desc ? x > y : x < y;

    private static int[] RangeIds(ArrayEntry[] a, int lo, int hi)
    {
        var ids = new int[hi - lo + 1];
        for (int i = lo; i <= hi; i++) ids[i - lo] = a[i].Id;
        return ids;
    }
}
