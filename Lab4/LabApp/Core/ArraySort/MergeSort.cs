namespace LabApp.Core.ArraySort;

/// <summary>
/// Сортировка слиянием (MergeSort) — усовершенствованный алгоритм, O(n·log n). Реализована
/// восходящая схема (bottom-up): сначала сливаем соседние серии длины 1, затем длины 2, 4, 8… —
/// длина отсортированных серий удваивается за проход, поэтому проходов ceil(log₂ n).
/// Каждое слияние двух серий честно использует буфер: сравниваем «головы» серий, меньшее
/// записываем в буфер; когда одна серия закончилась — остаток другой переписываем как есть.
/// В конце прохода буфер переписывается обратно в массив. При равных числах первым берётся
/// число из левой серии — сортировка устойчивая.
/// Вызовы builder всегда безусловные (счётчики нужны и в тихом режиме), строки описаний
/// строятся только в режиме трассировки — тернарные операторы не дают их собирать при замерах.
/// </summary>
public sealed class MergeSort : IArraySortAlgorithm
{
    public string Id => "merge";
    public string Title => "MergeSort (слиянием)";
    public string Group => ArraySortGroups.Advanced;
    public string Badge => "O(n·log n)";
    public string PassesLabel => "проходов";
    public int MemorySlots => 2;
    public string ShortInfo =>
        "Сливаем соседние отсортированные серии: длина 1 → 2 → 4 → 8… Сравниваем «головы» двух серий " +
        "и меньшее число записываем в буфер, в конце прохода буфер переписываем в массив. " +
        "В памяти: две «головы» серий.";

    public void Sort(ArrayEntry[] a, bool descending, ArraySortTraceBuilder b)
    {
        int n = a.Length;
        b.Phase("Знакомство",
            $"Перед нами массив из {n} чисел. Сортировка слиянием работает так: любые две соседние " +
            "отсортированные серии можно слить в одну — сравниваем их «головы» (первые числа) и меньшее " +
            "записываем в буфер. Начинаем с серий длины 1 (одно число — уже отсортированная серия): " +
            "после первого прохода серии длины 2, после второго — 4, и так далее, пока весь массив " +
            $"не станет одной серией. Проходов получится ⌈log₂ {n}⌉ — отсюда сложность O(n·log n): " +
            "на каждый проход уходит не больше n сравнений и 2n записей. " +
            $"Порядок: {(descending ? "по убыванию" : "по возрастанию")}.");

        if (n <= 1)
        {
            b.Done(n == 0
                ? "Массив пустой — сортировать нечего."
                : "Массив из одного числа уже отсортирован.");
            return;
        }

        var buf = new ArrayEntry[n]; // буфер слияния: на каждый проход переписываем в него весь массив
        for (int width = 1; width < n; width *= 2)
        {
            b.PassNext("Слияние серий", $"сливаем соседние серии длины {width}",
                b.Active
                    ? $"Проход с сериями длины {width}: берём пары соседних серий и сливаем каждую пару " +
                      "в одну отсортированную серию двойной длины. Записываем результат в буфер, " +
                      "а в конце прохода переписываем буфер обратно в массив."
                    : null,
                null, "В памяти будут две «головы» серий — когда дойдём до слияния.",
                clearBuffer: true); // буфер прошлого прохода неактуален

            for (int lo = 0; lo < n; lo += 2 * width)
            {
                int mid = Math.Min(lo + width, n) - 1;      // конец левой серии
                int hi = Math.Min(lo + 2 * width, n) - 1;   // конец правой серии
                Merge(a, lo, mid, hi, buf, descending, b);
            }

            for (int k = 0; k < n; k++) a[k] = buf[k]; // буфер целиком переписывается в массив
            b.CopyBack(n,
                b.Active
                    ? $"Проход закончен: переписываем буфер обратно в массив. Теперь все серии имеют длину " +
                      $"{Math.Min(width * 2, n)} — длина удвоилась."
                    : null,
                b.Active
                    ? $"✓ Буфер переписан в массив ({n} записей) — конец прохода"
                    : null,
                "Буфер очищен, память свободна до следующего прохода.");
        }

        b.MarkPlaced(Enumerable.Range(0, n).ToArray());
        b.Done(
            $"Готово: весь массив — одна отсортированная серия, числа стоят по " +
            $"{(descending ? "убыванию" : "возрастанию")}. Сравнений — {b.Comparisons}, " +
            $"записей (в буфер и обратно) — {b.Moves}, проходов — {b.Passes}.");
    }

    /// <summary>
    /// Слияние соседних серий a[lo..mid] и a[mid+1..hi] (обе уже отсортированы) в буфер.
    /// mid == hi значит правой серии нет — остаётся переписать серию в буфер как есть.
    /// Позиция в буфере совпадает с позицией в массиве: результат пары начинается с lo.
    /// </summary>
    private static void Merge(ArrayEntry[] a, int lo, int mid, int hi, ArrayEntry[] buf,
        bool desc, ArraySortTraceBuilder b)
    {
        // Размечаем серии для визуализации: чипы каждой серии обводятся своей группой с подписью.
        b.SetSeries(mid >= hi ? RangeIds(a, lo, hi) : RangeIds(a, lo, mid),
            mid >= hi ? [] : RangeIds(a, mid + 1, hi));

        if (b.Active)
            b.Note(
                mid >= hi
                    ? $"Серии [ {lo}..{mid} ] пары нет — переписываем её в буфер как есть (одно число — уже отсортированная серия)."
                    : $"Сливаем серии [ {lo}..{mid} ] и [ {mid + 1}..{hi} ]: обе уже отсортированы. " +
                      "Сравниваем их «головы» и меньшее число пишем в буфер.",
                mid >= hi
                    ? $"--- Серия [ {lo}..{mid} ] без пары → в буфер"
                    : $"--- Слияние [ {lo}..{mid} ] + [ {mid + 1}..{hi} ]",
                "В памяти две «головы» серий.",
                rangeIds: RangeIds(a, lo, hi));

        if (mid >= hi)
        {
            for (int i = lo; i <= hi; i++)
            {
                buf[i] = a[i]; // серия переписывается в буфер без изменений
                b.Write(i,
                    b.Active ? $"Серия без пары: «{a[i].Value}» переписывается в буфер (ячейка {i}) как есть." : null,
                    b.Active ? $"↔ Перестановка №{b.Moves + 1}: «{a[i].Value}» → буфер, ячейка {i}" : null,
                    "В памяти переписываемое число.");
            }
            b.ClearSeries();
            return;
        }

        int i2 = lo, j = mid + 1, k = lo;
        while (i2 <= mid && j <= hi)
        {
            // Равные числа берём из левой серии — сортировка устойчивая.
            bool takeLeft = desc ? a[i2].Value >= a[j].Value : a[i2].Value <= a[j].Value;
            b.Compare(i2, j,
                b.Active
                    ? $"Сравнили «головы» серий: «{a[i2].Value}» (позиция {i2}, левая) и «{a[j].Value}» " +
                      $"(позиция {j}, правая): {Relation(a[i2].Value, a[j].Value)}. " +
                      (takeLeft
                        ? $"В буфер идёт «{a[i2].Value}» из левой серии."
                        : $"В буфер идёт «{a[j].Value}» из правой серии.")
                    : null,
                b.Active
                    ? $"⚖ Сравнение №{b.Comparisons + 1}: слияние — «{a[i2].Value}» vs «{a[j].Value}» → " +
                      (takeLeft ? "из левой серии" : "из правой серии")
                    : null,
                $"В памяти «головы» серий: «{a[i2].Value}» и «{a[j].Value}».");

            int src = takeLeft ? i2 : j;
            buf[k] = a[src];
            b.Write(src,
                b.Active ? $"Записали «{a[src].Value}» в буфер (ячейка {k})." : null,
                b.Active ? $"↔ Перестановка №{b.Moves + 1}: «{a[src].Value}» → буфер, ячейка {k}" : null,
                $"В памяти «головы» серий: «{a[i2].Value}» и «{a[j].Value}».");
            if (takeLeft) i2++; else j++;
            k++;
        }

        for (; i2 <= mid; i2++, k++) // правая серия закончилась — остаток левой дописываем как есть
        {
            buf[k] = a[i2];
            b.Write(i2,
                b.Active ? $"Правая серия закончилась: «{a[i2].Value}» из остатка левой серии " +
                           $"переписывается в буфер (ячейка {k}) как есть." : null,
                b.Active ? $"↔ Перестановка №{b.Moves + 1}: «{a[i2].Value}» → буфер, ячейка {k}" : null,
                "В памяти переписываемое число.");
        }
        for (; j <= hi; j++, k++) // левая серия закончилась — остаток правой дописываем как есть
        {
            buf[k] = a[j];
            b.Write(j,
                b.Active ? $"Левая серия закончилась: «{a[j].Value}» из остатка правой серии " +
                           $"переписывается в буфер (ячейка {k}) как есть." : null,
                b.Active ? $"↔ Перестановка №{b.Moves + 1}: «{a[j].Value}» → буфер, ячейка {k}" : null,
                "В памяти переписываемое число.");
        }
        b.ClearSeries(); // пара слилась — группы серий с экрана убираются до следующей пары
    }

    // ---------------- служебные ----------------

    /// <summary>Человеческое описание результата сравнения двух чисел.</summary>
    private static string Relation(int x, int y)
    {
        if (x == y) return "числа одинаковые — берём из левой серии";
        return x < y ? $"«{x}» меньше «{y}»" : $"«{x}» больше «{y}»";
    }

    private static int[] RangeIds(ArrayEntry[] a, int lo, int hi)
    {
        var ids = new int[hi - lo + 1];
        for (int i = lo; i <= hi; i++) ids[i - lo] = a[i].Id;
        return ids;
    }
}
