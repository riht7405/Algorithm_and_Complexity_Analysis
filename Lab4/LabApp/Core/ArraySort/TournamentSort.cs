namespace LabApp.Core.ArraySort;

/// <summary>
/// Турнирная сортировка (TournamentSort) — усовершенствованный алгоритм, O(n·log n).
/// Числа играют «матчи» на выбывание: двое сравниваются, лучший (наименьшее при сортировке
/// по возрастанию) выходит в следующий круг. Все матчи образуют турнирную сетку — дерево,
/// в корне которого победитель всего турнира. Победитель уходит в выходной буфер, его
/// участник выбывает из сетки, и переигрывается только путь этого участника к корню —
/// около log₂ n матчей вместо полного перетурнира. Итого: n-1 матчей на построение сетки
/// плюс по ⌈log₂ n⌉ матчей на каждое из n извлечений — итого O(n·log n). При равных числах
/// матч выигрывает участник из левой части сетки — порядок равных сохраняется (сортировка
/// устойчивая). В конце выходной буфер переписывается в массив. В памяти одновременно
/// два значения: «в руке» — извлечённый победитель и соперник по матчу.
/// Вызовы builder всегда безусловные (счётчики нужны и в тихом режиме), строки описаний
/// строятся только в режиме трассировки — тернарные операторы не дают их собирать при замерах.
/// </summary>
public sealed class TournamentSort : IArraySortAlgorithm
{
    public string Id => "tournament";
    public string Title => "TournamentSort (турнирная)";
    public string Group => ArraySortGroups.Advanced;
    public string Badge => "O(n·log n)";
    public string PassesLabel => "извлечений";
    public int MemorySlots => 2;
    public string ShortInfo =>
        "Числа играют «матчи» на выбывание: лучший выходит в следующий круг, корень сетки — " +
        "победитель турнира. Извлекаем его в результат и переигрываем только его путь по сетке. " +
        "В памяти: победитель «в руке» и соперник.";

    public void Sort(ArrayEntry[] a, bool descending, ArraySortTraceBuilder b)
    {
        int n = a.Length;
        string best = descending ? "наибольшее" : "наименьшее";
        string order = descending ? "по убыванию" : "по возрастанию";

        b.Phase("Знакомство",
            $"Перед нами массив из {n} чисел. Турнирная сортировка устраивает «матчи» на выбывание: " +
            $"двое сравниваются, {best} выходит в следующий круг — так складывается турнирная сетка, " +
            "в корне которой победитель всего турнира. Победитель уходит в результат, его место " +
            "в сетке освобождается, и переигрывается только его путь к корню — около log₂ n матчей " +
            "вместо полного перетурнира. " +
            $"Порядок: {order}.");

        if (n <= 1)
        {
            b.Done(n == 0
                ? "Массив пустой — сортировать нечего."
                : "Массив из одного числа уже отсортирован.");
            return;
        }

        // Турнирная сетка: size листьев (ближайшая степень двойки >= n), tree[v] — позиция
        // массива, чьё число выигрывает в поддереве v, или -1, если участников не осталось.
        // Листья — позиции size-1 .. 2*size-2, дети узла p — 2p+1 и 2p+2.
        const int None = -1;
        int size = 1;
        while (size < n) size *= 2;
        var tree = new int[2 * size - 1];

        bool Better(int x, int y) => descending ? x > y : x < y; // «x лучше y» с учётом направления

        // ---------- этап 1: строим сетку — соседние пары играют круг за кругом ----------
        b.PassNext("Построение сетки", "соседние пары играют круг за кругом",
            b.Active
                ? $"Участники — все {n} чисел. Играем круг за кругом: пары соседних участников, " +
                  $"{best} идёт дальше. На построение уходит n-1 = {n - 1} матчей."
                : null,
            Enumerable.Range(0, n).Select(i => a[i].Id).ToArray(),
            "В памяти участники текущего матча.");

        for (int i = 0; i < size; i++)
            tree[size - 1 + i] = i < n ? i : None; // листья — позиции; добивка — свободные места

        for (int p = size - 2; p >= 0; p--)
        {
            int c1 = 2 * p + 1, c2 = 2 * p + 2;
            int w1 = tree[c1], w2 = tree[c2];
            if (w1 == None) tree[p] = w2;         // соперника нет — свободный выход в следующий круг
            else if (w2 == None) tree[p] = w1;
            else
            {
                // При равных числах матч выигрывает участник из левой части — сортировка устойчивая.
                bool firstBest = Better(a[w1].Value, a[w2].Value) || a[w1].Value == a[w2].Value;
                int winner = firstBest ? w1 : w2;
                b.Compare(w1, w2,
                    b.Active
                        ? $"Матч: «{a[w1].Value}» (позиция {w1}) против «{a[w2].Value}» (позиция {w2}): " +
                          $"{MatchResult(a[w1].Value, a[w2].Value, descending, best)}. " +
                          $"В следующий круг идёт «{a[winner].Value}»."
                        : null,
                    b.Active
                        ? $"⚖ Матч: «{a[w1].Value}» vs «{a[w2].Value}» → «{a[winner].Value}»"
                        : null,
                    "В памяти участники матча.", winner);
                tree[p] = winner;
            }
        }

        // ---------- этап 2: извлекаем победителей и переигрываем путь по сетке ----------
        var output = new ArrayEntry[n]; // выход: победители в порядке извлечения
        for (int k = 0; k < n; k++)
        {
            int win = tree[0];
            b.PassNext("Извлечение", $"победитель — «{a[win].Value}»",
                b.Active
                    ? $"Извлечение {k + 1}: в корне сетки {best} — «{a[win].Value}» (позиция {win}). " +
                      "Записываем его в результат, участник выбывает, и его путь к корню " +
                      "переигрывается заново — победители подпирают снизу."
                    : null,
                [a[win].Id],
                "В памяти извлечённый победитель.");

            int leaf = size - 1 + win;
            tree[leaf] = None; // участник выбыл
            int v = (leaf - 1) / 2;
            while (v >= 0)
            {
                int c1 = 2 * v + 1, c2 = 2 * v + 2;
                int w1 = tree[c1], w2 = tree[c2];
                if (w1 == None) tree[v] = w2;      // в этом матче соперник один — свободный проход
                else if (w2 == None) tree[v] = w1;
                else
                {
                    bool firstBest = Better(a[w1].Value, a[w2].Value) || a[w1].Value == a[w2].Value;
                    int winner = firstBest ? w1 : w2;
                    b.Compare(w1, w2,
                        b.Active
                            ? $"Переигрываем путь: матч «{a[w1].Value}» (позиция {w1}) против " +
                              $"«{a[w2].Value}» (позиция {w2}): {MatchResult(a[w1].Value, a[w2].Value, descending, best)}. " +
                              $"Подпирает снизу «{a[winner].Value}»."
                            : null,
                        b.Active
                            ? $"⚖ Матч: «{a[w1].Value}» vs «{a[w2].Value}» → «{a[winner].Value}»"
                            : null,
                        "В памяти участники матча.", winner);
                    tree[v] = winner;
                }

                if (v == 0) break;
                v = (v - 1) / 2;
            }

            output[k] = a[win];
            b.Write(win,
                b.Active
                    ? $"Победитель «{a[win].Value}» записан в выход — это позиция результата {k}."
                    : null,
                b.Active
                    ? $"↔ Перестановка №{b.Moves + 1}: «{a[win].Value}» → выход"
                    : null,
                "В памяти записанное число.");
        }

        // ---------- этап 3: выход переписывается в массив — он и есть отсортированный порядок ----------
        for (int k = 0; k < n; k++) a[k] = output[k];
        b.CopyBack(n,
            b.Active
                ? $"Сетка опустела: все {n} победителей записаны в выход по порядку. Переписываем " +
                  "выход в массив — теперь он отсортирован."
                : null,
            b.Active
                ? $"↔ Буфер → массив: {n} чисел переписаны на свои места"
                : null,
            "Массив упорядочен.");

        b.MarkPlaced(Enumerable.Range(0, n).ToArray());
        b.Done(
            $"Готово: все числа стоят по {order}. " +
            $"Сравнений — {b.Comparisons}, перестановок — {b.Moves}, извлечений — {b.Passes - 1}.");
    }

    // ---------------- служебные ----------------

    /// <summary>Человеческое описание результата матча двух чисел.</summary>
    private static string MatchResult(int x, int y, bool desc, string best)
    {
        if (x == y) return "числа одинаковые — дальше идёт левый участник";
        bool xBetter = desc ? x > y : x < y;
        return xBetter
            ? $"«{x}» — {best}, идёт дальше"
            : $"«{y}» — {best}, идёт дальше";
    }
}
